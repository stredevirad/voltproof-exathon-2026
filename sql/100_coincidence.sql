-- 100_coincidence.sql
-- Potential shared supply events (METHODOLOGY R-19..R-21). Wording rule: these are coincidences between
-- independent monitors, never "faults". Parameters from PARAMS (coincidence.*).
--
-- Performance note: a partner interruption must start 0..DELTA minutes later. With time buckets of width
-- >= DELTA, it lies in the same or the next bucket, so each band join is two plain equality joins
-- (bucket + 0, bucket + 1) on materialised tables. Each pair is found exactly once. (A single
-- non-equality band join over the shifted copies took 348 s on the 2018 Jun-Aug UP sample; this takes ~2 s.)

CREATE OR REPLACE TABLE INTERRUPTION AS
SELECT e.EVENT_ID, e.EVENT_KEY, e.LOCATION_ID, l.DISTRICT, l.STATE_NAME, e.START_TS, e.END_TS, e.MIN_DURATION,
       CAST(TRUNC(e.START_TS, 'MM') AS DATE) AS MONTH_START,
       COALESCE((SELECT m.IS_COMPARABLE FROM MONTHLY m
                 WHERE m.LOCATION_ID = e.LOCATION_ID AND m.MONTH_START = CAST(TRUNC(e.START_TS, 'MM') AS DATE)),
                FALSE) AS IS_COMPARABLE_MONTH,
       CAST(FLOOR(MINUTES_BETWEEN(e.START_TS, TIMESTAMP '2000-01-01 00:00:00')
                  / GREATEST((SELECT NUM_VALUE FROM PARAMS WHERE NAME = 'coincidence.max_start_offset_minutes'), 1))
            AS DECIMAL(12,0)) AS BUCKET
FROM EVENT e
JOIN LOCATION l ON l.LOCATION_ID = e.LOCATION_ID
WHERE e.IS_INTERRUPTION;

-- R-19: each coincident pair once; A is the earlier start (ties: lower LOCATION_ID).
CREATE OR REPLACE TABLE COINCIDENT_PAIR AS
WITH P AS (
    SELECT MAX(CASE WHEN NAME = 'coincidence.max_start_offset_minutes' THEN NUM_VALUE END) AS DELTA,
           MAX(CASE WHEN NAME = 'coincidence.min_overlap_minutes'      THEN NUM_VALUE END) AS THETA
    FROM PARAMS
), C AS (
    SELECT a.DISTRICT, a.EVENT_ID AS EVENT_A, b.EVENT_ID AS EVENT_B, a.LOCATION_ID AS LOCATION_A,
           b.LOCATION_ID AS LOCATION_B, a.START_TS AS START_A, b.START_TS AS START_B, a.END_TS AS END_A,
           b.END_TS AS END_B
    FROM INTERRUPTION a JOIN INTERRUPTION b ON b.DISTRICT = a.DISTRICT AND b.BUCKET = a.BUCKET
    UNION ALL
    SELECT a.DISTRICT, a.EVENT_ID, b.EVENT_ID, a.LOCATION_ID, b.LOCATION_ID, a.START_TS, b.START_TS,
           a.END_TS, b.END_TS
    FROM INTERRUPTION a JOIN INTERRUPTION b ON b.DISTRICT = a.DISTRICT AND b.BUCKET = a.BUCKET + 1
)
SELECT C.DISTRICT, C.EVENT_A, C.EVENT_B, C.LOCATION_A, C.LOCATION_B, C.START_A, C.START_B, C.END_A, C.END_B,
       CAST(MINUTES_BETWEEN(C.START_B, C.START_A) AS DECIMAL(6,0))                              AS START_OFFSET_MIN,
       CAST(MINUTES_BETWEEN(LEAST(C.END_A, C.END_B), GREATEST(C.START_A, C.START_B)) + 1 AS DECIMAL(12,0)) AS OVERLAP_MIN
FROM C CROSS JOIN P
WHERE C.LOCATION_B <> C.LOCATION_A
  AND C.START_B BETWEEN C.START_A AND ADD_MINUTES(C.START_A, P.DELTA)
  AND (C.START_B > C.START_A OR C.LOCATION_B > C.LOCATION_A)
  AND MINUTES_BETWEEN(LEAST(C.END_A, C.END_B), GREATEST(C.START_A, C.START_B)) + 1 >= P.THETA;

-- R-20: start-time chains per district (break when consecutive starts are more than DELTA apart).
CREATE OR REPLACE TABLE COINCIDENCE_CHAIN AS
WITH P AS (
    SELECT MAX(CASE WHEN NAME = 'coincidence.max_start_offset_minutes' THEN NUM_VALUE END) AS DELTA FROM PARAMS
), O AS (
    SELECT i.EVENT_ID, i.DISTRICT, i.LOCATION_ID, i.START_TS, i.END_TS,
           CASE WHEN MINUTES_BETWEEN(i.START_TS,
                       LAG(i.START_TS) OVER (PARTITION BY i.DISTRICT ORDER BY i.START_TS, i.LOCATION_ID)) <= P.DELTA
                THEN 0 ELSE 1 END AS IS_NEW
    FROM INTERRUPTION i CROSS JOIN P
)
SELECT EVENT_ID, DISTRICT, LOCATION_ID, START_TS, END_TS,
       SUM(IS_NEW) OVER (PARTITION BY DISTRICT ORDER BY START_TS, LOCATION_ID
                         ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS CHAIN_NO
FROM O;

-- Members: chain events that take part in at least one coincident pair.
CREATE OR REPLACE TABLE POTENTIAL_SHARED_MEMBER_TMP AS
SELECT c.DISTRICT, c.CHAIN_NO, c.EVENT_ID, c.LOCATION_ID, c.START_TS, c.END_TS
FROM COINCIDENCE_CHAIN c
WHERE c.EVENT_ID IN (SELECT EVENT_A FROM COINCIDENT_PAIR UNION SELECT EVENT_B FROM COINCIDENT_PAIR);

CREATE OR REPLACE TABLE POTENTIAL_SHARED_EVENT AS
WITH G AS (
    SELECT DISTRICT, CHAIN_NO, MIN(START_TS) AS START_TS, MAX(END_TS) AS END_TS,
           COUNT(*) AS N_MEMBERS, COUNT(DISTINCT LOCATION_ID) AS N_LOCATIONS
    FROM POTENTIAL_SHARED_MEMBER_TMP
    GROUP BY DISTRICT, CHAIN_NO
), PC AS (
    SELECT c.DISTRICT, c.CHAIN_NO, COUNT(*) AS N_PAIRS
    FROM COINCIDENT_PAIR p
    JOIN COINCIDENCE_CHAIN c ON c.EVENT_ID = p.EVENT_A
    GROUP BY c.DISTRICT, c.CHAIN_NO
)
SELECT CAST(ROW_NUMBER() OVER (ORDER BY G.DISTRICT, G.START_TS) AS DECIMAL(18,0)) AS GROUP_ID,
       G.DISTRICT || ' | ' || TO_CHAR(G.START_TS, 'YYYY-MM-DD HH24:MI')          AS GROUP_KEY,
       G.DISTRICT, G.CHAIN_NO, G.START_TS, G.END_TS, G.N_MEMBERS, G.N_LOCATIONS,
       COALESCE(PC.N_PAIRS, 0) AS N_PAIRS
FROM G
LEFT JOIN PC ON PC.DISTRICT = G.DISTRICT AND PC.CHAIN_NO = G.CHAIN_NO;

CREATE OR REPLACE TABLE POTENTIAL_SHARED_MEMBER AS
SELECT g.GROUP_ID, g.GROUP_KEY, m.EVENT_ID, (SELECT i.EVENT_KEY FROM INTERRUPTION i WHERE i.EVENT_ID = m.EVENT_ID) AS EVENT_KEY,
       m.LOCATION_ID, m.DISTRICT, m.START_TS, m.END_TS,
       CAST(MINUTES_BETWEEN(m.START_TS, g.START_TS) AS DECIMAL(6,0)) AS OFFSET_FROM_GROUP_START_MIN
FROM POTENTIAL_SHARED_MEMBER_TMP m
JOIN POTENTIAL_SHARED_EVENT g ON g.DISTRICT = m.DISTRICT AND g.CHAIN_NO = m.CHAIN_NO;

DROP TABLE POTENTIAL_SHARED_MEMBER_TMP;

-- R-21 chance baseline. Step 0: the interruptions that enter the comparison (D-023: comparable
-- location-months only, unless coincidence.baseline_comparable_only = 0).
CREATE OR REPLACE TABLE BASELINE_INTERRUPTION AS
SELECT i.*
FROM INTERRUPTION i
WHERE COALESCE((SELECT NUM_VALUE FROM PARAMS WHERE NAME = 'coincidence.baseline_comparable_only'), 1) = 0
   OR i.IS_COMPARABLE_MONTH;

-- Step 1: shifted copies of every baseline interruption (K = 0 is the unshifted data).
CREATE OR REPLACE TABLE BASELINE_SHIFTED AS
WITH P AS (
    SELECT MAX(CASE WHEN NAME = 'coincidence.max_start_offset_minutes' THEN NUM_VALUE END) AS DELTA,
           MAX(CASE WHEN NAME = 'coincidence.baseline_shifts'          THEN NUM_VALUE END) AS N
    FROM PARAMS
), L AS (   -- index j of each location within its district-month (locations with >= 1 interruption)
    SELECT DISTRICT, MONTH_START, LOCATION_ID,
           ROW_NUMBER() OVER (PARTITION BY DISTRICT, MONTH_START ORDER BY LOCATION_ID) - 1 AS J
    FROM (SELECT DISTINCT DISTRICT, MONTH_START, LOCATION_ID FROM BASELINE_INTERRUPTION) x
), K AS (
    SELECT CAST(LEVEL - 1 AS DECIMAL(6,0)) AS K FROM DUAL CONNECT BY LEVEL <= 1001
), S AS (
    SELECT i.DISTRICT, i.MONTH_START, k.K, i.LOCATION_ID, P.DELTA,
           ADD_DAYS(i.START_TS,
                    MOD(DAY(i.START_TS) - 1 + MOD(l.J * k.K, DAYS_BETWEEN(ADD_MONTHS(i.MONTH_START, 1), i.MONTH_START)),
                        DAYS_BETWEEN(ADD_MONTHS(i.MONTH_START, 1), i.MONTH_START)) + 1 - DAY(i.START_TS)) AS START_TS,
           MINUTES_BETWEEN(i.END_TS, i.START_TS) AS DUR_MIN
    FROM BASELINE_INTERRUPTION i
    JOIN L l ON l.DISTRICT = i.DISTRICT AND l.MONTH_START = i.MONTH_START AND l.LOCATION_ID = i.LOCATION_ID
    CROSS JOIN P
    JOIN K k ON k.K <= P.N
)
SELECT DISTRICT, MONTH_START, K, LOCATION_ID, START_TS, ADD_MINUTES(START_TS, DUR_MIN) AS END_TS,
       CAST(FLOOR(MINUTES_BETWEEN(START_TS, TIMESTAMP '2000-01-01 00:00:00') / GREATEST(DELTA, 1))
            AS DECIMAL(12,0)) AS BUCKET
FROM S;

-- Step 2: coincident pairs per district-month and shift (both events start in that month by construction).
CREATE OR REPLACE TABLE BASELINE_PAIRS AS
WITH P AS (
    SELECT MAX(CASE WHEN NAME = 'coincidence.max_start_offset_minutes' THEN NUM_VALUE END) AS DELTA,
           MAX(CASE WHEN NAME = 'coincidence.min_overlap_minutes'      THEN NUM_VALUE END) AS THETA
    FROM PARAMS
), C AS (
    SELECT a.DISTRICT, a.MONTH_START, a.K, a.LOCATION_ID AS LA, b.LOCATION_ID AS LB,
           a.START_TS AS SA, b.START_TS AS SB, a.END_TS AS EA, b.END_TS AS EB
    FROM BASELINE_SHIFTED a
    JOIN BASELINE_SHIFTED b
      ON b.DISTRICT = a.DISTRICT AND b.MONTH_START = a.MONTH_START AND b.K = a.K AND b.BUCKET = a.BUCKET
    UNION ALL
    SELECT a.DISTRICT, a.MONTH_START, a.K, a.LOCATION_ID, b.LOCATION_ID, a.START_TS, b.START_TS, a.END_TS, b.END_TS
    FROM BASELINE_SHIFTED a
    JOIN BASELINE_SHIFTED b
      ON b.DISTRICT = a.DISTRICT AND b.MONTH_START = a.MONTH_START AND b.K = a.K AND b.BUCKET = a.BUCKET + 1
)
SELECT C.DISTRICT, C.MONTH_START, C.K, COUNT(*) AS PAIRS
FROM C CROSS JOIN P
WHERE C.LB <> C.LA
  AND C.SB BETWEEN C.SA AND ADD_MINUTES(C.SA, P.DELTA)
  AND (C.SB > C.SA OR C.LB > C.LA)
  AND MINUTES_BETWEEN(LEAST(C.EA, C.EB), GREATEST(C.SA, C.SB)) + 1 >= P.THETA
GROUP BY C.DISTRICT, C.MONTH_START, C.K;

-- Step 3: observed vs expected per district-month; shifts with no pair count as zero.
CREATE OR REPLACE TABLE COINCIDENCE_BASELINE AS
WITH P AS (
    SELECT MAX(CASE WHEN NAME = 'coincidence.baseline_shifts' THEN NUM_VALUE END) AS N,
           COALESCE(MAX(CASE WHEN NAME = 'coincidence.baseline_comparable_only' THEN NUM_VALUE END), 1) AS CO
    FROM PARAMS
), DM AS (
    SELECT DISTRICT, MONTH_START, COUNT(DISTINCT LOCATION_ID) AS N_LOCATIONS, COUNT(*) AS N_INTERRUPTIONS
    FROM BASELINE_INTERRUPTION GROUP BY DISTRICT, MONTH_START
), K AS (
    SELECT CAST(LEVEL AS DECIMAL(6,0)) AS K FROM DUAL CONNECT BY LEVEL <= 1000
), GRID AS (
    SELECT dm.DISTRICT, dm.MONTH_START, k.K, COALESCE(bp.PAIRS, 0) AS PAIRS
    FROM DM dm
    CROSS JOIN P
    JOIN K k ON k.K <= P.N
    LEFT JOIN BASELINE_PAIRS bp ON bp.DISTRICT = dm.DISTRICT AND bp.MONTH_START = dm.MONTH_START AND bp.K = k.K
), OBS AS (
    SELECT dm.DISTRICT, dm.MONTH_START, COALESCE(bp.PAIRS, 0) AS OBSERVED
    FROM DM dm
    LEFT JOIN BASELINE_PAIRS bp ON bp.DISTRICT = dm.DISTRICT AND bp.MONTH_START = dm.MONTH_START AND bp.K = 0
)
SELECT dm.DISTRICT,
       TO_CHAR(dm.MONTH_START, 'YYYY-MM')                                          AS MONTH_KEY,
       CASE WHEN MAX(P.CO) = 0 THEN FALSE ELSE TRUE END                          AS COMPARABLE_ONLY,
       dm.N_LOCATIONS,
       dm.N_INTERRUPTIONS,
       CAST(o.OBSERVED AS DECIMAL(12,0))                                           AS OBSERVED_PAIRS,
       CAST(SUM(g.PAIRS) / MAX(P.N) AS DECIMAL(18,6))                              AS EXPECTED_PAIRS,
       CAST(SUM(CASE WHEN g.PAIRS >= o.OBSERVED THEN 1 ELSE 0 END) / MAX(P.N) AS DECIMAL(9,6)) AS P_VALUE,
       CAST(MAX(P.N) AS DECIMAL(6,0))                                              AS N_SHIFTS
FROM DM dm
JOIN OBS o  ON o.DISTRICT = dm.DISTRICT AND o.MONTH_START = dm.MONTH_START
JOIN GRID g ON g.DISTRICT = dm.DISTRICT AND g.MONTH_START = dm.MONTH_START
CROSS JOIN P
GROUP BY dm.DISTRICT, dm.MONTH_START, dm.N_LOCATIONS, dm.N_INTERRUPTIONS, o.OBSERVED;
