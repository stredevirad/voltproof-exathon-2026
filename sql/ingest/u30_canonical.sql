INSERT INTO RAW_HOURLY (FILE_ID, LINE_NO, LOCATION_NAME, DATE_STR, HOUR_STR,
    M00, M01, M02, M03, M04, M05, M06, M07, M08, M09, M10, M11, M12, M13, M14, M15, M16, M17, M18, M19,
    M20, M21, M22, M23, M24, M25, M26, M27, M28, M29, M30, M31, M32, M33, M34, M35, M36, M37, M38, M39,
    M40, M41, M42, M43, M44, M45, M46, M47, M48, M49, M50, M51, M52, M53, M54, M55, M56, M57, M58, M59)
SELECT FILE_ID, MIN(LINE_NO), LOC, TO_CHAR(HOUR_TS, 'DD-MM-YYYY'), CAST(HOUR(HOUR_TS) AS VARCHAR(2)),
    MAX(CASE WHEN MI = 0 THEN V END),  MAX(CASE WHEN MI = 1 THEN V END),  MAX(CASE WHEN MI = 2 THEN V END),
    MAX(CASE WHEN MI = 3 THEN V END),  MAX(CASE WHEN MI = 4 THEN V END),  MAX(CASE WHEN MI = 5 THEN V END),
    MAX(CASE WHEN MI = 6 THEN V END),  MAX(CASE WHEN MI = 7 THEN V END),  MAX(CASE WHEN MI = 8 THEN V END),
    MAX(CASE WHEN MI = 9 THEN V END),  MAX(CASE WHEN MI = 10 THEN V END), MAX(CASE WHEN MI = 11 THEN V END),
    MAX(CASE WHEN MI = 12 THEN V END), MAX(CASE WHEN MI = 13 THEN V END), MAX(CASE WHEN MI = 14 THEN V END),
    MAX(CASE WHEN MI = 15 THEN V END), MAX(CASE WHEN MI = 16 THEN V END), MAX(CASE WHEN MI = 17 THEN V END),
    MAX(CASE WHEN MI = 18 THEN V END), MAX(CASE WHEN MI = 19 THEN V END), MAX(CASE WHEN MI = 20 THEN V END),
    MAX(CASE WHEN MI = 21 THEN V END), MAX(CASE WHEN MI = 22 THEN V END), MAX(CASE WHEN MI = 23 THEN V END),
    MAX(CASE WHEN MI = 24 THEN V END), MAX(CASE WHEN MI = 25 THEN V END), MAX(CASE WHEN MI = 26 THEN V END),
    MAX(CASE WHEN MI = 27 THEN V END), MAX(CASE WHEN MI = 28 THEN V END), MAX(CASE WHEN MI = 29 THEN V END),
    MAX(CASE WHEN MI = 30 THEN V END), MAX(CASE WHEN MI = 31 THEN V END), MAX(CASE WHEN MI = 32 THEN V END),
    MAX(CASE WHEN MI = 33 THEN V END), MAX(CASE WHEN MI = 34 THEN V END), MAX(CASE WHEN MI = 35 THEN V END),
    MAX(CASE WHEN MI = 36 THEN V END), MAX(CASE WHEN MI = 37 THEN V END), MAX(CASE WHEN MI = 38 THEN V END),
    MAX(CASE WHEN MI = 39 THEN V END), MAX(CASE WHEN MI = 40 THEN V END), MAX(CASE WHEN MI = 41 THEN V END),
    MAX(CASE WHEN MI = 42 THEN V END), MAX(CASE WHEN MI = 43 THEN V END), MAX(CASE WHEN MI = 44 THEN V END),
    MAX(CASE WHEN MI = 45 THEN V END), MAX(CASE WHEN MI = 46 THEN V END), MAX(CASE WHEN MI = 47 THEN V END),
    MAX(CASE WHEN MI = 48 THEN V END), MAX(CASE WHEN MI = 49 THEN V END), MAX(CASE WHEN MI = 50 THEN V END),
    MAX(CASE WHEN MI = 51 THEN V END), MAX(CASE WHEN MI = 52 THEN V END), MAX(CASE WHEN MI = 53 THEN V END),
    MAX(CASE WHEN MI = 54 THEN V END), MAX(CASE WHEN MI = 55 THEN V END), MAX(CASE WHEN MI = 56 THEN V END),
    MAX(CASE WHEN MI = 57 THEN V END), MAX(CASE WHEN MI = 58 THEN V END), MAX(CASE WHEN MI = 59 THEN V END)
FROM (
    SELECT FILE_ID, LINE_NO, SUBSTR(LOC, 1, 300) AS LOC, SUBSTR(V, 1, 40) AS V,
           TRUNC(TS, 'HH') AS HOUR_TS, MINUTE(TS) AS MI
    FROM UPLOAD_LONG_PARSED
    WHERE TS IS NOT NULL
) R
GROUP BY FILE_ID, LOC, HOUR_TS;

