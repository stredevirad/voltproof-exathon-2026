--                dates in DD-MM-YYYY, hours 0-23, cells unchanged (cut at 40 characters, the raw column width).
--   long layout: readings pivoted in SQL to one RAW_HOURLY row per monitor and clock hour; a minute without a
--                reading stays an empty cell, so step 030 treats it as no reading (NO_DATA), never as outage.
--                The row's line number is the first line of that hour in the uploaded file.
--   typed locations: district and state entered on the upload page become RAW_LOCATION rows (file 800000003).
-- File ids 800000001-800000003 are fixed for uploads (never a Dataverse id or a synthetic id).

