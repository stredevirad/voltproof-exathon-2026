"""Write docs/BENCHMARKS.md from the recorded runs in docs/benchmarks/*.jsonl (pipeline/benchmark.py).
No number in BENCHMARKS.md is typed by hand.

Usage: .venv\\Scripts\\python.exe -m pipeline.benchmark_report
"""

from __future__ import annotations

import json
import re
import statistics
import subprocess
from pathlib import Path

from pipeline.run_sql import SQL_DIR, split_statements

REPO_ROOT = Path(__file__).resolve().parents[1]
DATA = REPO_ROOT / "docs" / "benchmarks"
OUT = REPO_ROOT / "docs" / "BENCHMARKS.md"

# Key statements shown individually: (step file, target object) -> label
KEY = {
    ("030_unpivot.sql", "MINUTE_RAW"): "Unpivot 63-column hour rows to minutes (in-database)",
    ("030_unpivot.sql", "MINUTE_READING"): "Type and validate minute values",
    ("040_clean.sql", "REPEATED_MINUTE"): "Duplicate detection (hour level first, D-028)",
    ("040_clean.sql", "READING_CLEAN"): "Clean readings",
    ("050_segments.sql", "MEASURED_RUN"): "Run detection, gaps-and-islands (window function, D-028)",
    ("050_segments.sql", "SEGMENT"): "Segments including NO_DATA gaps",
    ("060_events.sql", "EVENT"): "Outage events with certainty and bounds",
    ("080_daily.sql", "DAILY"): "Daily aggregates (full calendar)",
    ("095_quality.sql", "QUALITY_LOCATION"): "Data-quality per location",
    ("100_coincidence.sql", "COINCIDENT_PAIR"): "Coincident pairs (bucketed band join, D-021)",
    ("100_coincidence.sql", "BASELINE_PAIRS"): "Chance baseline pairs, 20 shifts (D-021)",
}


def _load(kind: str) -> list[dict]:
    p = DATA / f"{kind}.jsonl"
    return [json.loads(x) for x in p.read_text(encoding="utf-8").splitlines() if x.strip()] if p.exists() else []


def _targets() -> dict[tuple[str, int], str]:
    out = {}
    for f in sorted(SQL_DIR.glob("[0-9][0-9][0-9]_*.sql")):
        for i, s in enumerate(split_statements(f.read_text(encoding="utf-8")), 1):
            m = re.search(r"(?:TABLE|VIEW)\s+(?:IF\s+EXISTS\s+)?(\w+)", s, re.I)
            out[(f.name, i)] = m.group(1).upper() if m else "?"
    return out


def _mr(xs: list[float], unit: str = "s", nd: int = 1) -> str:
    xs = [x for x in xs if x is not None]
    if not xs:
        return "–"
    med = statistics.median(xs)
    if len(xs) == 1:
        return f"{med:.{nd}f} {unit}"
    return f"{med:.{nd}f} {unit} ({min(xs):.{nd}f}–{max(xs):.{nd}f})"


def _prov(runs: list[dict]) -> str:
    if not runs:
        return "–"
    texts = [" ".join(b["provenance"]) for b in runs]
    if all("different=0 missing=0" in t for t in texts):
        return f"all matched in {len(runs)} of {len(runs)} runs (0 different, 0 missing)"
    return "; ".join(texts)


def _git() -> str:
    return subprocess.run(["git", "rev-parse", "--short=12", "HEAD"], cwd=REPO_ROOT, capture_output=True, text=True,
                          check=False).stdout.strip()


def render() -> str:
    env = (_load("env") or [{}])[-1]
    builds = _load("build")
    queries = _load("queries")
    hist = (_load("history") or [{"statements": []}])[-1]["statements"]
    tgt = _targets()
    failed = [b for b in builds if b.get("status") == "failed"]
    builds = [b for b in builds if b.get("status") != "failed"]
    by_mode = {m: [b for b in builds if b["mode"] == m] for m in ("cold", "warm")}
    L = [
        "# Benchmarks",
        "",
        "Every number below comes from a recorded run in `docs/benchmarks/*.jsonl`, written by",
        "`pipeline/benchmark.py`; this file is generated by `pipeline/benchmark_report.py` (commit "
        f"`{_git()}` when generated). Medians, with the range in brackets.",
        "",
        "## Environment",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Machine | {env.get('processor', '?')}, {env.get('logical_cpus', '?')} logical CPUs, "
        f"{env.get('host_ram_gib', '?')} GiB RAM (Intel Core Ultra 5 125H) |",
        f"| OS | {env.get('os', '?')} |",
        f"| Database | Exasol Personal {env.get('exasol_version', '?')}, local deployment (Podman machine on WSL 2), "
        "DB RAM 8.9 GiB, data volume on D: |",
        f"| Free host RAM / disk when recorded | {env.get('free_ram_gib', '?')} GiB; C: {env.get('disk_free_gib', {}).get('C')} GiB, "
        f"D: {env.get('disk_free_gib', {}).get('D')} GiB |",
        "| Conditions | App server stopped, Docker Desktop not running, one build at a time |",
        "",
        "**Cold** = the first run after `scripts\\exa.ps1 stop` and `start` (database caches empty; the data volume "
        "already grown; the Windows file cache is not cleared). **Warm** = repeated runs with the database running.",
        "",
    ]
    if builds:
        b0 = builds[-1]
        L += [
            "## Full Uttar Pradesh build (IMPORT of every file + all analytical SQL)",
            "",
            f"Input: {b0['load_rows']:,} raw rows in {len(b0['load_files'])} files → {b0['clean_minutes']:,} clean "
            f"minute readings → {b0['events']:,} outage events; {b0['statements']} SQL statements. Command: "
            "`python -m pipeline.build` (what `scripts\\load.ps1` runs after verifying the files).",
            "",
            "| Measure | Cold | Warm |",
            "|---|---:|---:|",
            f"| Runs | {len(by_mode['cold'])} | {len(by_mode['warm'])} |",
            f"| Wall time, whole build | {_mr([b['wall_seconds'] for b in by_mode['cold']])} | "
            f"{_mr([b['wall_seconds'] for b in by_mode['warm']])} |",
            f"| Native IMPORT of all files | {_mr([b['load_seconds'] for b in by_mode['cold']])} | "
            f"{_mr([b['load_seconds'] for b in by_mode['warm']])} |",
            f"| All analytical SQL statements | {_mr([b['sql_seconds'] for b in by_mode['cold']])} | "
            f"{_mr([b['sql_seconds'] for b in by_mode['warm']])} |",
            f"| Database restart before the run | {_mr([b['restart_seconds'] for b in by_mode['cold']])} | – |",
            f"| Lowest free host RAM during the run | {_mr([b['min_free_ram_gib_during'] for b in by_mode['cold']], 'GiB', 2)} | "
            f"{_mr([b['min_free_ram_gib_during'] for b in by_mode['warm']], 'GiB', 2)} |",
            f"| Provenance check after each run (every RUN_LOG statement vs the audit log) | {_prov(by_mode['cold'])} | "
            f"{_prov(by_mode['warm'])} |",
            "",
            "### Key statements",
            "",
            "Wall time as seen by the pipeline; DB time, CPU and temporary-memory peak from Exasol's "
            "`EXA_DBA_AUDIT_SQL` (warm runs).",
            "",
            "| Statement | Rows | Cold | Warm | DB time (warm) | CPU % (warm) | Temp RAM peak (warm) |",
            "|---|---:|---:|---:|---:|---:|---:|",
        ]
        for (step, target), label in KEY.items():
            def pick(runs, field, step=step, target=target):
                return [s.get(field) for b in runs for s in b["steps"]
                        if s["step"] == step and tgt.get((step, s["stmt_index"])) == target]
            rows = pick(builds, "rows")
            L.append(f"| {label} (`{target}`) | {int(rows[-1]):,} | {_mr(pick(by_mode['cold'], 'wall_seconds'))} | "
                     f"{_mr(pick(by_mode['warm'], 'wall_seconds'))} | {_mr(pick(by_mode['warm'], 'db_seconds'))} | "
                     f"{_mr(pick(by_mode['warm'], 'cpu_pct'), '%', 0)} | "
                     f"{_mr(pick(by_mode['warm'], 'temp_ram_peak_mib'), 'MiB', 0)} |" if rows else f"| {label} | – |")
        if failed:
            L += ["", "### Failed runs (excluded from the statistics above)", ""]
            for f in failed:
                L.append(f"- {f['mode']} run started {f['started_local']}: " + " ".join(f.get("error", [])))
            L += ["", "The loader now retries a dropped IMPORT transfer once, after rolling back that file (D-032).",
                  "Retries are recorded per file in each run's `load_files[].attempts`."]
        L += ["", "### All SQL steps (sum of statement wall times per step file)", "",
              "| Step | Cold | Warm |", "|---|---:|---:|"]
        steps = sorted({s["step"] for b in builds for s in b["steps"]})
        for st in steps:
            def per_run(runs, st=st):
                return [sum(s["wall_seconds"] for s in b["steps"] if s["step"] == st) for b in runs]
            L.append(f"| `{st}` | {_mr(per_run(by_mode['cold']))} | {_mr(per_run(by_mode['warm']))} |")
        L.append("")
    if hist:
        cur = {}
        for b in by_mode["warm"]:
            for s in b["steps"]:
                cur.setdefault(tgt.get((s["step"], s["stmt_index"])), []).append(s["wall_seconds"])
        L += [
            "## Three scale fixes: before and after",
            "",
            "\"Before\" = earlier formulations as recorded in Exasol's audit log on 2026-10-11 (times UTC); they "
            "are not re-run, because the 040 one held 8–10 GiB of temporary memory and left the host with under "
            "1 GB free. \"After\" = the warm runs above (full UP data).",
            "",
            "| Fix | Before (audit log) | After (warm median) |",
            "|---|---|---|",
        ]
        def h(target, ok=None):
            return [s for s in hist if f"TABLE {target} " in s["sql_head"] and (ok is None or s["success"] == ok)]
        for target, fix, data in [
            ("COINCIDENCE_BASELINE", "D-021 chance baseline: band join → two bucketed equality joins", "2018 Jun–Aug sample (49 monitors)"),
            ("READING_CLEAN", "D-028 duplicates: GROUP BY over 90 M minute groups → hour-level detection first", "full UP"),
            ("READING_CONFLICT", "D-028 (same build, next statement)", "full UP"),
            ("MEASURED_RUN", "D-028 runs: LAG + running SUM → one ROW_NUMBER window", "full UP"),
        ]:
            for s in h(target):
                state = "completed" if s["success"] else f"cancelled ({s['error_code']})"
                after_targets = (["BASELINE_INTERRUPTION", "BASELINE_SHIFTED", "BASELINE_PAIRS", "COINCIDENCE_BASELINE"]
                                 if target == "COINCIDENCE_BASELINE" else
                                 ["REPEATED_HOUR", "REPEATED_MINUTE", "READING_CLEAN", "READING_CONFLICT"]
                                 if target in ("READING_CLEAN", "READING_CONFLICT") else [target])
                runs = len(by_mode["warm"])
                tot = [sum(cur.get(t, [0] * runs)[i] for t in after_targets) for i in range(runs)] if runs else []
                L.append(f"| {fix} | {s['db_seconds']:.0f} s, {state}, temp RAM {s['temp_ram_peak_mib'] or 0:,.0f} MiB "
                         f"({data}, {s['start_utc'][:16]}) | {_mr(tot)} for {' + '.join(after_targets)} (full UP) |")
        L += ["",
              "The D-021 \"before\" ran on the 2018 June–August sample only; the \"after\" column is the full Uttar "
              "Pradesh data, so the comparison understates the gain.", ""]
    if queries:
        L += ["## Interactive queries (guided-demo path, in-process through the API's service functions)", "",
              "First call after a restart (cold) and the following calls (warm).", "",
              "| Call | Cold: first call | Warm: median (range) |", "|---|---:|---:|"]
        names = list(queries[-1]["timings"])
        for n in names:
            cold = [q["timings"][n][0] for q in queries if q["mode"] == "cold"]
            warm = [t for q in queries for t in (q["timings"][n][1:] if q["mode"] == "cold" else q["timings"][n])]
            L.append(f"| {n} | {_mr(cold, 's', 2)} | {_mr(warm, 's', 3)} |")
        L.append("")
    L += ["## Reproduce", "", "```powershell",
          ".venv\\Scripts\\python.exe -m pipeline.benchmark env",
          ".venv\\Scripts\\python.exe -m pipeline.benchmark history",
          ".venv\\Scripts\\python.exe -m pipeline.benchmark build --runs 3          # warm",
          ".venv\\Scripts\\python.exe -m pipeline.benchmark build --runs 3 --cold   # restarts the database before each run",
          ".venv\\Scripts\\python.exe -m pipeline.benchmark queries --runs 5 --cold",
          ".venv\\Scripts\\python.exe -m pipeline.benchmark_report",
          "```", ""]
    return "\n".join(L)


def main() -> None:
    OUT.write_text(render(), encoding="utf-8", newline="\n")
    print(OUT.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
