"""Generate THIRD_PARTY_NOTICES.md: licences of the Python and npm dependencies (runtime + dev).

    .venv\\Scripts\\python.exe -m pipeline.third_party_notices
"""

from __future__ import annotations

import json
import sys
from importlib import metadata
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]


def python_packages() -> list[tuple[str, str, str]]:
    out = []
    for dist in metadata.distributions():
        name = dist.metadata.get("Name") or "?"
        lic = dist.metadata.get("License-Expression") or ""
        if not lic:
            classifiers = [c.split("::")[-1].strip() for c in (dist.metadata.get_all("Classifier") or [])
                           if c.startswith("License ::")]
            lic = "; ".join(classifiers) or (dist.metadata.get("License") or "").splitlines()[0][:80] if (
                classifiers or dist.metadata.get("License")) else "UNKNOWN"
        out.append((name, dist.version, lic or "UNKNOWN"))
    return sorted(set(out), key=lambda t: t[0].lower())


def npm_packages() -> list[tuple[str, str, str]]:
    root = REPO_ROOT / "app" / "web" / "node_modules"
    out = []
    for pj in root.glob("**/package.json"):
        rel = pj.relative_to(root).parts
        # top-level packages: name/package.json or @scope/name/package.json
        if not ((len(rel) == 2) or (len(rel) == 3 and rel[0].startswith("@"))):
            continue
        try:
            d = json.loads(pj.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        lic = d.get("license") or (d.get("licenses") or [{}])[0].get("type") if isinstance(d.get("licenses"), list) else d.get("license")
        if isinstance(lic, dict):
            lic = lic.get("type")
        if d.get("name"):
            out.append((d["name"], d.get("version", "?"), lic or "UNKNOWN"))
    return sorted(set(out), key=lambda t: t[0].lower())


def main() -> int:
    py, js = python_packages(), npm_packages()
    lines = [
        "# Third-party notices",
        "",
        "VoltProof's own code is MIT-licensed (LICENSE). It depends on the open-source packages below, each under its",
        "own licence. Generated by `pipeline/third_party_notices.py` from the installed package metadata.",
        "",
        "Other software used, not redistributed: **Exasol Personal** (proprietary, free for personal use; installing",
        "it accepts the Exasol Personal EULA), the **Exasol Launcher** (MIT), **Podman** (Apache-2.0),",
        "**Playwright Chromium** (BSD-3-Clause / Chromium licences) and **gitleaks** (MIT).",
        "",
        "Data: ESMI minute-wise voltage data, Prayas (Energy Group), Harvard Dataverse doi:10.7910/DVN/CLLZZM, CC0 1.0",
        "plus Prayas's terms of use (docs/data/SOURCE_TERMS.md). The data is not part of this repository.",
        "",
        f"## Python packages ({len(py)})",
        "",
        "| Package | Version | Licence |",
        "|---|---|---|",
        *[f"| {n} | {v} | {lic} |" for n, v, lic in py],
        "",
        f"## npm packages ({len(js)}, top-level in app/web/node_modules)",
        "",
        "| Package | Version | Licence |",
        "|---|---|---|",
        *[f"| {n} | {v} | {lic} |" for n, v, lic in js],
        "",
    ]
    (REPO_ROOT / "THIRD_PARTY_NOTICES.md").write_text("\n".join(lines), encoding="utf-8")
    unknown = [n for n, _, lic in py + js if lic == "UNKNOWN"]
    print(f"python={len(py)} npm={len(js)} unknown-licence={unknown}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
