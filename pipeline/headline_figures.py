"""Headline figures for the README, deck and JUDGE_QA, computed once from Exasol and written to
docs/HEADLINE_FIGURES.md (D-031: outage and coincidence headlines use 2016-2018, the validated years; scale
figures describe the full load).

Precondition: the UP build (scripts\\load.ps1) and the validation step (python -m pipeline.run_sql 110).
Usage: .venv\\Scripts\\python.exe -m pipeline.headline_figures
"""

from __future__ import annotations

import datetime as dt
import subprocess
from pathlib import Path

from pipeline.db import DEFAULT_SCHEMA, connect, require_real_data

REPO_ROOT = Path(__file__).resolve().parents[1]
OUT = REPO_ROOT / "docs" / "HEADLINE_FIGURES.md"
CUTOFF = "2019-01-01"  # headline aggregates: months before this date


def _git() -> str:
    out = subprocess.run(["git", "rev-parse", "--short=12", "HEAD"], cwd=REPO_ROOT, capture_output=True, text=True,
                         check=False)
    dirty = subprocess.run(["git", "status", "--porcelain", "--untracked-files=no"], cwd=REPO_ROOT,
                           capture_output=True, text=True, check=False).stdout.strip()
    return (out.stdout.strip() or "unknown") + (" + uncommitted changes" if dirty else "")


def collect(c) -> dict:
    one = lambda sql: c.execute(sql).fetchone()
    f = {}
    f["scale"] = one("""SELECT (SELECT COUNT(*) FROM SOURCE_FILE WHERE FILE_KIND = 'readings'),
                               (SELECT COUNT(*) FROM RAW_HOURLY),
                               (SELECT SUM(READINGS_CLEAN) FROM QUALITY_LOCATION),
                               (SELECT COUNT(*) FROM QUALITY_LOCATION),
                               (SELECT COUNT(*) FROM EVENT),
                               (SELECT COUNT(*) FROM EVENT WHERE IS_INTERRUPTION),
                               (SELECT COUNT(*) FROM DAILY),
                               (SELECT COUNT(*) FROM MONTHLY),
                               (SELECT SUM(CASE WHEN IS_COMPARABLE THEN 1 ELSE 0 END) FROM MONTHLY),
                               (SELECT COUNT(*) FROM COINCIDENT_PAIR),
                               (SELECT COUNT(*) FROM POTENTIAL_SHARED_EVENT),
                               (SELECT MIN(FIRST_TS) FROM QUALITY_LOCATION), (SELECT MAX(LAST_TS) FROM QUALITY_LOCATION)
                        FROM DUAL""")
    f["categories"] = c.execute(f"""
        SELECT PRAYAS_CATEGORY, COUNT(DISTINCT LOCATION_ID), COUNT(*), ROUND(SUM(OBS_DAYS), 1),
               ROUND(SUM(OUTAGE_MIN_LOWER) / SUM(OBS_DAYS), 1), ROUND(SUM(INTERRUPTIONS) / SUM(OBS_DAYS), 2),
               ROUND(SUM(EVENING_OUTAGE_LOWER) / SUM(OBS_EVENINGS), 1), SUM(INTERRUPTIONS)
        FROM VALIDATION_LM WHERE MONTH_START < DATE '{CUTOFF}' GROUP BY PRAYAS_CATEGORY ORDER BY 1""").fetchall()
    f["all_up"] = one(f"""SELECT COUNT(DISTINCT LOCATION_ID), COUNT(*), SUM(INTERRUPTIONS),
                                 ROUND(SUM(OUTAGE_MIN_LOWER) / SUM(OBS_DAYS), 1), MIN(MONTH_START), MAX(MONTH_START)
                          FROM VALIDATION_LM WHERE MONTH_START < DATE '{CUTOFF}'""")
    f["coincidence"] = one(f"""
        SELECT COUNT(*), SUM(CASE WHEN P_VALUE = 0 THEN 1 ELSE 0 END), SUM(OBSERVED_PAIRS), ROUND(SUM(EXPECTED_PAIRS), 1),
               MAX(N_SHIFTS)
        FROM COINCIDENCE_BASELINE WHERE N_LOCATIONS >= 2 AND MONTH_KEY < '{CUTOFF[:7]}'""")
    f["coincidence_median"] = one(f"""SELECT MEDIAN(OBSERVED_PAIRS / EXPECTED_PAIRS), COUNT(*) FROM COINCIDENCE_BASELINE
                                      WHERE N_LOCATIONS >= 2 AND EXPECTED_PAIRS >= 10 AND MONTH_KEY < '{CUTOFF[:7]}'""")
    f["shared_events"] = one(f"SELECT COUNT(*) FROM POTENTIAL_SHARED_EVENT WHERE START_TS < TIMESTAMP '{CUTOFF} 00:00:00'")
    return f


def render(f: dict, schema: str) -> str:
    n = lambda v: f"{int(v):,}"
    s = f["scale"]
    a = f["all_up"]
    co = f["coincidence"]
    med = f["coincidence_median"]
    lines = [
        "# Headline figures",
        "",
        f"Generated by `pipeline/headline_figures.py` from schema `{schema}` at commit `{_git()}` on "
        f"{dt.datetime.now().strftime('%Y-%m-%d %H:%M')} IST. Do not edit by hand; re-run the script.",
        "",
        "Rule (D-031): **outage and coincidence headlines use 2016–2018**, the years validated against Prayas's",
        "single-monitor charts. January–June 2019 stays in the app with a lower-bound warning. **Scale figures**",
        "describe everything loaded and analysed.",
        "",
        "## Scale (full Uttar Pradesh load)",
        "",
        "| Measure | Value |",
        "|---|---:|",
        f"| Source data files loaded (2019 July–Dec loaded but excluded, D-026) | {n(s[0])} |",
        f"| Raw location-hour rows loaded (all states in the files) | {n(s[1])} |",
        f"| Clean minute readings analysed (in scope) | {n(s[2])} |",
        f"| Monitors in scope | {n(s[3])} |",
        f"| Outage events (interruptions: ≥ 1 measured minute ≤ 130 V) | {n(s[5])} |",
        f"| Location-days / location-months (comparable) | {n(s[6])} / {n(s[7])} ({n(s[8])}) |",
        f"| Coincident interruption pairs / potential shared supply events | {n(s[9])} / {n(s[10])} |",
        f"| First and last reading | {str(s[11])[:16]} to {str(s[12])[:16]} |",
        "",
        "## Outage headlines, 2016–2018 (comparable location-months, Prayas's categories, D-030)",
        "",
        f"All UP: {n(a[0])} monitors, {n(a[1])} comparable location-months ({str(a[4])[:7]} to {str(a[5])[:7]}), "
        f"{n(a[2])} interruptions, **{a[3]} minutes of outage per day** (pooled).",
        "",
        "| Category | Monitors | Location-months | Observed days | Outage min/day | Interruptions/day | Evening outage min (17–23 h) |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for cat, mon, lm, days, out, ints, eve, _ in f["categories"]:
        lines.append(f"| {cat} | {n(mon)} | {n(lm)} | {float(days):,.1f} | {out} | {ints} | {eve} |")
    lines += [
        "",
        "Measured minutes only (lower bounds); missing data is never counted as outage.",
        "",
        "## Potential shared supply events vs chance, 2016–2018",
        "",
        f"- District-months with at least two monitors: {n(co[0])}; above all {n(co[4])} shifted variants: {n(co[1])}.",
        f"- Coincident pairs observed: {n(co[2])}; expected by chance: {float(co[3]):,.1f} "
        f"({float(co[2]) / float(co[3]):.1f} times).",
        f"- Median observed/expected over the {n(med[1])} district-months with at least 10 expected pairs: "
        f"{float(med[0]):.1f}.",
        f"- Potential shared supply events starting in 2016–2018: {n(f['shared_events'][0])}.",
        "",
        "Coincidence is not cause: these are interruptions at different monitors that started within 2 minutes of",
        "each other, compared with a time-shifted baseline (METHODOLOGY R-19 to R-21).",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    require_real_data(DEFAULT_SCHEMA, "Headline figures")
    with connect(schema=DEFAULT_SCHEMA) as c:
        f = collect(c)
    OUT.write_text(render(f, DEFAULT_SCHEMA), encoding="utf-8", newline="\n")
    print(OUT.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
