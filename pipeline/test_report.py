"""Write docs/TEST_REPORT.md from the JUnit XML and run metadata that scripts\\test.ps1 leaves in reports\\tests\\.
Nothing in TEST_REPORT.md is typed by hand.

Usage: scripts\\test.ps1 ; then .venv\\Scripts\\python.exe -m pipeline.test_report
"""

from __future__ import annotations

import json
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DIR = REPO_ROOT / "reports" / "tests"
OUT = REPO_ROOT / "docs" / "TEST_REPORT.md"
SUITES = ["unit", "integration", "differential", "e2e"]
WHAT = {
    "unit": "No database: claims vocabulary, published-text scan, tracked-file sizes, source compile check, "
            "download checks, loader edge cases, SYNTHETIC demo generator (deterministic, labelled)",
    "integration": "Hand-written fixtures through the real SQL in Exasol, oracle equality, harness sensitivity, "
                   "evidence-report consistency, SYNTHETIC demo set (separation guards, oracle equality)",
    "differential": "Independent oracle vs SQL on random Hypothesis batches and on real Uttar Pradesh slices",
    "e2e": "Playwright drives the guided demo in Chromium against a real server; wording scan on every page; "
           "SYNTHETIC banner and no real-data figures on the demo set",
}


def _meta() -> dict:
    """Merge every run_meta_*.json of this campaign (whole suites or parts, see scripts\\test.ps1 -Part)."""
    metas = [json.loads(p.read_text(encoding="utf-8-sig")) for p in sorted(DIR.glob("run_meta_*.json"))]
    if not metas:
        return {}
    merged = {"commit": ", ".join(sorted({m.get("commit") or "unknown" for m in metas})),
              "uncommitted_files": max(int(m.get("uncommitted_files") or 0) for m in metas),
              "started": min(m.get("started", "?") for m in metas), "finished": max(m.get("finished", "?") for m in metas),
              "schema": ", ".join(sorted({m.get("schema", "?") for m in metas})),
              "hypothesis_examples": ", ".join(sorted({str(m.get("hypothesis_examples", "?")) for m in metas})),
              "parts": sorted(m["part"] for m in metas if m.get("part"))}
    for s in SUITES:
        walls = [float(m[f"wall_seconds_{s}"]) for m in metas if f"wall_seconds_{s}" in m]
        if walls:
            merged[f"wall_seconds_{s}"] = sum(walls)
    return merged


def _suite(name: str) -> dict | None:
    files = sorted([*DIR.glob(f"{name}.xml"), *DIR.glob(f"{name}+*.xml")])
    if not files:
        return None
    parts = [_one(p) for p in files]
    return {"tests": sum(p["tests"] for p in parts), "failures": sum(p["failures"] for p in parts),
            "errors": sum(p["errors"] for p in parts), "skipped": sum(p["skipped"] for p in parts),
            "time": sum(p["time"] for p in parts), "cases": [c for p in parts for c in p["cases"]]}


def _one(p: Path) -> dict:
    root = ET.parse(p).getroot()
    ts = root if root.tag == "testsuite" else root.find("testsuite")
    cases = []
    for tc in ts.iter("testcase"):
        outcome = "passed"
        for tag in ("failure", "error", "skipped"):
            el = tc.find(tag)
            if el is not None:
                outcome = {"failure": "FAILED", "error": "ERROR", "skipped": "skipped"}[tag]
                if tag == "skipped":
                    outcome += f" ({(el.get('message') or '').strip()[:80]})"
        cases.append({"file": tc.get("classname", "").rsplit(".", 1)[0].replace(".", "/") + ".py",
                      "name": tc.get("name"), "time": float(tc.get("time") or 0), "outcome": outcome})
    return {"tests": int(ts.get("tests", 0)), "failures": int(ts.get("failures", 0)), "errors": int(ts.get("errors", 0)),
            "skipped": int(ts.get("skipped", 0)), "time": float(ts.get("time", 0)), "timestamp": ts.get("timestamp"),
            "cases": cases}


def render() -> str:
    meta = _meta()
    suites = {s: _suite(s) for s in SUITES}
    commit = meta.get("commit", "unknown")
    dirty = meta.get("uncommitted_files")
    L = ["# Test report", "",
         "Generated by `pipeline/test_report.py` from the JUnit XML that `scripts\\test.ps1` wrote. Do not edit by hand.",
         "",
         f"- **Tested commit:** `{commit}`" + (" (clean working tree)" if dirty == 0 else
                                              f" with {dirty} uncommitted tracked file(s)" if dirty else ""),
         f"- **Run:** {meta.get('started', '?')} to {meta.get('finished', '?')} (local time); schema "
         f"`{meta.get('schema', '?')}`; Hypothesis examples per test: {meta.get('hypothesis_examples', '?')}",
         *([f"- **Run in parts** (`scripts\\test.ps1 -Suite <suite> -Part <path>`, to keep each command under 10 "
            f"minutes): {', '.join(f'`{x}`' for x in meta['parts'])}"] if meta.get("parts") else []),
         "", "| Suite | What it checks | Tests | Passed | Failed | Errors | Skipped | Time |",
         "|---|---|---:|---:|---:|---:|---:|---:|"]
    tot = defaultdict(float)
    for s, r in suites.items():
        if not r:
            L.append(f"| {s} | {WHAT[s]} | not run | | | | | |")
            continue
        passed = r["tests"] - r["failures"] - r["errors"] - r["skipped"]
        wall = meta.get(f"wall_seconds_{s}", r["time"])
        L.append(f"| {s} | {WHAT[s]} | {r['tests']} | {passed} | {r['failures']} | {r['errors']} | {r['skipped']} | "
                 f"{float(wall):.0f} s |")
        for k in ("tests", "failures", "errors", "skipped"):
            tot[k] += r[k]
        tot["passed"] += passed
        tot["time"] += float(wall)
    L.append(f"| **Total** | | **{int(tot['tests'])}** | **{int(tot['passed'])}** | {int(tot['failures'])} | "
             f"{int(tot['errors'])} | {int(tot['skipped'])} | {tot['time']:.0f} s |")
    L += ["", "## Every test", ""]
    for s, r in suites.items():
        if not r:
            continue
        L += [f"### {s}", "", "| Test | Outcome | Time |", "|---|---|---:|"]
        for c in r["cases"]:
            L.append(f"| `{c['file']}::{c['name']}` | {c['outcome']} | {c['time']:.2f} s |")
        L.append("")
    return "\n".join(L)


def main() -> None:
    OUT.write_text(render(), encoding="utf-8", newline="\n")
    print(OUT.read_text(encoding="utf-8")[:3000])


if __name__ == "__main__":
    main()
